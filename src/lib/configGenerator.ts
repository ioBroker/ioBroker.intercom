/** Logger levels of Asterisk for each log level of the adapter */
const LOGGER_LEVELS: Record<AsteriskLogLevel, string> = {
    none: '',
    errors: 'error,warning',
    notice: 'error,warning,notice',
    verbose: 'error,warning,notice,verbose(3)',
    debug: 'error,warning,notice,verbose(5),debug',
};

/** Verbosity of the Asterisk core, set by AMI: verbose(N) only logs what the core produces */
export function getLogCommands(level: AsteriskLogLevel, sipTrace: boolean): string[] {
    return [
        `core set verbose ${level === 'debug' ? 5 : 3}`,
        level === 'debug' ? 'core set debug 3' : 'core set debug off',
        `pjsip set logger ${sipTrace ? 'on' : 'off'}`,
    ];
}

function genLogger(config: GeneratorConfig): string {
    const level = ASTERISK_LOG_LEVELS.includes(config.logLevel as AsteriskLogLevel)
        ? (config.logLevel as AsteriskLogLevel)
        : 'errors';
    const lines = [
        HEADER,
        '[general]',
        // milliseconds help to correlate with the ioBroker log
        'dateformat=%F %T.%3q',
        'appendhostname=no',
        '',
        '[logfiles]',
        // the container log (docker logs) keeps the important messages
        'console => notice,warning,error',
    ];
    if (LOGGER_LEVELS[level]) {
        lines.push(`${LOG_FILE.replace('logs/', '')} => ${LOGGER_LEVELS[level]}`);
    }
    lines.push('');
    return lines.join('\n');
}

/**
 * Entry point of the container. The image is a plain `ubuntu:24.04`: Asterisk (with res_srtp, WSS
 * transport and PJSIP) is installed by apt the first time the container starts and stays in the
 * container until it is recreated.
 */
export function genStartScript(): string {
    return `#!/bin/bash
# generated by ioBroker intercom – do not edit
set -u
DIR=${CONTAINER_DIR}

if ! command -v asterisk >/dev/null 2>&1; then
    echo "[iobroker] Installing Asterisk. This takes a few minutes on the first start..."
    export DEBIAN_FRONTEND=noninteractive
    if ! (apt-get update && apt-get install -y --no-install-recommends \\
            asterisk asterisk-modules asterisk-core-sounds-en-gsm ca-certificates); then
        echo "[iobroker] Installation of Asterisk failed. Retrying in 60 seconds."
        sleep 60
        exit 1
    fi
    # Not all distributions ship an opus codec module - it is optional
    apt-get install -y --no-install-recommends asterisk-opus >/dev/null 2>&1 || true
    rm -rf /var/lib/apt/lists/*
fi

# Music on hold (a phone puts a call on hold). Separate check: also for containers installed before
if [ ! -d /usr/share/asterisk/moh ]; then
    export DEBIAN_FRONTEND=noninteractive
    (apt-get update && apt-get install -y --no-install-recommends asterisk-moh-opsound-gsm) >/dev/null 2>&1 \\
        || echo "[iobroker] Music on hold could not be installed"
    rm -rf /var/lib/apt/lists/*
fi

# ARI (REST interface) is not used: disabled, otherwise it complains about missing users
printf '[general]\\nenabled = no\\n' > /etc/asterisk/ari.conf

# The configuration files of Asterisk only include the generated files
for f in http pjsip rtp extensions manager modules logger; do
    echo "#include iobroker/$f.conf" > /etc/asterisk/$f.conf
done
# Asterisk runs as root in the container: it must read the key files of the host (mode 0600)
sed -i -E 's/^\\s*(runuser|rungroup)/;\\1/' /etc/asterisk/asterisk.conf

# Static files (test page) are served from the generated directory
mkdir -p "$DIR/static-http"
rm -rf /usr/share/asterisk/static-http
ln -s "$DIR/static-http" /usr/share/asterisk/static-http

echo "[iobroker] Starting Asterisk $(asterisk -V 2>/dev/null)"
exec asterisk -f -vvv
`;
}

/**
 * Generate all files from the configuration.
 *
 * @param config the not secret part of the configuration
 * @param secrets decrypted secrets
 * @param assets static files shipped with the adapter
 * @param assets.phone content of the phone bundle (React + MUI + JsSIP) for the test page
 */
export function generateConfig(
    config: GeneratorConfig,
    secrets: GeneratorSecrets,
    assets: { phone?: string } = {},
): GeneratorResult {
    const { subscribers, warnings } = validateSubscribers(config, secrets);

    const files: Record<string, string> = {
        'http.conf': genHttp(config),
        'pjsip.conf': genPjsip(config, secrets, subscribers),
        'rtp.conf': genRtp(config),
        'extensions.conf': genExtensions(config, subscribers),
        'manager.conf': genManager(config, secrets),
        'modules.conf': genModules(),
        'logger.conf': genLogger(config),
        'start.sh': genStartScript(),
        'keys/asterisk.crt': secrets.certPublic || '',
        'keys/asterisk.key': secrets.certPrivate || '',
        [`static-http/${CERT_FILE}`]: generateCertPage(),
    };
    if (config.testPage) {
        // the browser calls the phone: the first SIP subscriber (101 of a new installation), else the echo test
        const sipPhone = subscribers.find(s => s.kind === 'sip');
        files['static-http/test.html'] = generateTestPage(
            sipPhone ? sipPhone.extension : config.echoTest ? ECHO_EXTENSION : '',
        );
        if (assets.phone) {
            files[`static-http/${PHONE_FILE}`] = assets.phone;
        }
    }
    return { files, warnings, subscribers };
}

/** Which Asterisk modules must be reloaded for the changed files */
export function getReloadCommands(changedFiles: string[]): string[] {
    const commands: string[] = [];
    if (changedFiles.includes('pjsip.conf')) {
        commands.push('module reload res_pjsip.so');
    }
    if (changedFiles.includes('extensions.conf')) {
        commands.push('dialplan reload');
    }
    if (changedFiles.some(f => f === 'http.conf' || f.startsWith('keys/'))) {
        commands.push('module reload http');
    }
    if (changedFiles.includes('rtp.conf')) {
        commands.push('module reload res_rtp_asterisk.so');
    }
    if (changedFiles.includes('logger.conf')) {
        commands.push('logger reload');
    }
    if (changedFiles.includes('manager.conf')) {
        commands.push('manager reload');
    }
    return commands;
}
