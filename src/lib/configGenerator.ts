/**
 * Pure generator of all files that Asterisk reads from `/etc/asterisk/iobroker/`.
 *
 * No I/O, no time, no randomness: the same input always produces the same output, so the result
 * can be hashed to decide whether Asterisk has to reload, and it can be snapshot tested.
 */
import { createHash } from 'node:crypto';
import type { Codec, SubscriberKind, VideoCodec } from '../types';
import { CERT_FILE, generateCertPage, generateTestPage, PHONE_FILE } from './testPage';

export const HEADER = '; generated by ioBroker intercom – do not edit';
export const REALM = 'iobroker';
export const CONTEXT = 'iobroker';
export const AMI_USER = 'iobroker';
export const ECHO_EXTENSION = '600';
/** Minimal length of a subscriber password */
export const MIN_PASSWORD_LENGTH = 4;
/** Directory of the generated files inside the container */
export const CONTAINER_DIR = '/etc/asterisk/iobroker';

/** Files with secrets in clear text - written with mode 0600 */
export const SECRET_FILES = ['manager.conf', 'keys/asterisk.key'];
/** Files that require a restart of Asterisk (or of the container) instead of a reload */
export const RESTART_FILES = ['start.sh', 'modules.conf', 'manager.conf'];

export const ALL_CODECS: Codec[] = ['opus', 'g722', 'ulaw', 'alaw'];
export const ALL_VIDEO_CODECS: VideoCodec[] = ['vp8', 'h264', 'vp9'];

/** How much Asterisk writes into the log file that the adapter forwards to the ioBroker log */
export type AsteriskLogLevel = 'none' | 'errors' | 'notice' | 'verbose' | 'debug';
export const ASTERISK_LOG_LEVELS: AsteriskLogLevel[] = ['none', 'errors', 'notice', 'verbose', 'debug'];
/** Directory of the log files inside the container, bind mounted to `<configDir>/logs` */
export const CONTAINER_LOG_DIR = '/var/log/asterisk';
/** Log file read by the adapter, relative to the configuration directory */
export const LOG_FILE = 'logs/iobroker.log';

export interface GeneratorSubscriber {
    extension: string;
    name: string;
    kind: SubscriberKind;
    enabled: boolean;
}

export interface GeneratorConfig {
    amiPort: number;
    wssPort: number;
    rtpStart: number;
    rtpEnd: number;
    stunServer: string;
    externalAddress: string;
    iceDenylist: string;
    codecs: Codec[];
    /** Passed through between the parties, never transcoded. Empty or missing: audio only */
    videoCodecs?: VideoCodec[];
    echoTest: boolean;
    testPage: boolean;
    /** What Asterisk writes into the log file for ioBroker */
    logLevel?: AsteriskLogLevel;
    subscribers: GeneratorSubscriber[];
}

export interface GeneratorSecrets {
    amiSecret: string;
    /** Clear text passwords by extension */
    passwords: Record<string, string>;
    certPublic: string;
    certPrivate: string;
}

export interface GeneratorResult {
    /** Relative file name => content */
    files: Record<string, string>;
    /** Problems found during validation. The affected subscribers were skipped */
    warnings: string[];
    /** Subscribers that made it into the configuration */
    subscribers: GeneratorSubscriber[];
}

/**
 * Remove everything that could break out of a value in an Asterisk config file:
 * line breaks, comments (`;`), section headers (`[` `]`), quotes and the angle brackets of a CallerID.
 */
export function sanitizeName(name: string): string {
    return Array.from(String(name ?? ''))
        .filter(ch => ch.charCodeAt(0) >= 0x20 && ch.charCodeAt(0) !== 0x7f && !'"<>;[]\\'.includes(ch))
        .join('')
        .trim()
        .substring(0, 64);
}

/** Only allow a strict set of characters for host names, IP addresses, ports and network lists */
export function sanitizeHost(value: string): string {
    return String(value ?? '')
        .trim()
        .replace(/[^A-Za-z0-9.:_/,-]/g, '');
}

export function isValidExtension(extension: string): boolean {
    return /^[0-9]{2,6}$/.test(extension);
}

function toPort(value: number, def: number): number {
    const port = Math.round(Number(value));
    return port > 0 && port < 65536 ? port : def;
}

export function md5Credential(extension: string, password: string, realm = REALM): string {
    return createHash('md5').update(`${extension}:${realm}:${password}`).digest('hex');
}

/** Validate subscribers: invalid, duplicate or disabled entries are dropped */
export function validateSubscribers(
    config: GeneratorConfig,
    secrets: GeneratorSecrets,
): { subscribers: GeneratorSubscriber[]; warnings: string[] } {
    const warnings: string[] = [];
    const used = new Set<string>();
    const subscribers: GeneratorSubscriber[] = [];

    for (const sub of config.subscribers || []) {
        const extension = String(sub?.extension ?? '').trim();
        if (!sub || !sub.enabled) {
            continue;
        }
        if (!isValidExtension(extension)) {
            warnings.push(`Subscriber "${sanitizeName(extension)}" skipped: invalid extension (2-6 digits)`);
            continue;
        }
        if (config.echoTest && extension === ECHO_EXTENSION) {
            warnings.push(`Subscriber ${extension} skipped: ${ECHO_EXTENSION} is reserved for the echo test`);
            continue;
        }
        if (used.has(extension)) {
            warnings.push(`Subscriber ${extension} skipped: duplicate extension`);
            continue;
        }
        const password = secrets.passwords[extension] || '';
        if (password.length < MIN_PASSWORD_LENGTH) {
            warnings.push(
                `Subscriber ${extension} skipped: password must have at least ${MIN_PASSWORD_LENGTH} characters`,
            );
            continue;
        }
        used.add(extension);
        subscribers.push({
            extension,
            name: sanitizeName(sub.name) || extension,
            kind: sub.kind === 'sip' ? 'sip' : 'webrtc',
            enabled: true,
        });
    }
    return { subscribers, warnings };
}

function codecList(codecs: Codec[], kind: SubscriberKind, videoCodecs: VideoCodec[] = []): string {
    let list = (codecs || []).filter(c => ALL_CODECS.includes(c));
    if (kind === 'sip') {
        // Desk phones and door intercoms rarely talk opus
        list = list.filter(c => c !== 'opus');
    }
    if (!list.length) {
        list = ['ulaw', 'alaw'];
    }
    const video = (videoCodecs || []).filter(c => ALL_VIDEO_CODECS.includes(c));
    return [...new Set<string>([...list, ...video])].join(',');
}

function genHttp(config: GeneratorConfig): string {
    return [
        HEADER,
        '[general]',
        'enabled=yes',
        // plain HTTP only for local use, WSS for the clients
        'bindaddr=127.0.0.1',
        'bindport=8088',
        'tlsenable=yes',
        `tlsbindaddr=0.0.0.0:${toPort(config.wssPort, 8089)}`,
        `tlscertfile=${CONTAINER_DIR}/keys/asterisk.crt`,
        `tlsprivatekey=${CONTAINER_DIR}/keys/asterisk.key`,
        // static-http holds only the generated pages: the certificate page always, the test page if enabled
        'enablestatic=yes',
        '',
    ].join('\n');
}

function genPjsip(config: GeneratorConfig, secrets: GeneratorSecrets, subscribers: GeneratorSubscriber[]): string {
    const lines: string[] = [HEADER, ''];
    const externalAddress = sanitizeHost(config.externalAddress);
    const hasSip = subscribers.some(s => s.kind === 'sip');

    lines.push('[global]', 'type=global', `default_realm=${REALM}`, 'user_agent=ioBroker PBX', '');

    // Clients in these networks keep getting the local address, all others the external one
    const nat = externalAddress
        ? [
              `external_media_address=${externalAddress}`,
              `external_signaling_address=${externalAddress}`,
              'local_net=10.0.0.0/8',
              'local_net=172.16.0.0/12',
              'local_net=192.168.0.0/16',
          ]
        : [];

    lines.push('[transport-wss]', 'type=transport', 'protocol=wss', 'bind=0.0.0.0', ...nat, '');

    if (hasSip) {
        lines.push('[transport-udp]', 'type=transport', 'protocol=udp', 'bind=0.0.0.0:5060', ...nat, '');
    }

    lines.push(
        '; ---- templates ----',
        '[webrtc-endpoint](!)',
        'type=endpoint',
        `context=${CONTEXT}`,
        'transport=transport-wss',
        'disallow=all',
        `allow=${codecList(config.codecs, 'webrtc', config.videoCodecs)}`,
        // webrtc=yes implies use_avpf, media_encryption=dtls, dtls_verify=fingerprint,
        // dtls_setup=actpass, ice_support, media_use_received_transport and rtcp_mux
        'webrtc=yes',
        'dtls_auto_generate_cert=yes',
        'direct_media=no',
        'allow_subscribe=no',
        '',
        '[sip-endpoint](!)',
        'type=endpoint',
        `context=${CONTEXT}`,
        'transport=transport-udp',
        'disallow=all',
        `allow=${codecList(config.codecs, 'sip', config.videoCodecs)}`,
        'direct_media=no',
        'rtp_symmetric=yes',
        'force_rport=yes',
        'rewrite_contact=yes',
        'allow_subscribe=no',
        '',
        '[aor-template](!)',
        'type=aor',
        'max_contacts=5',
        'remove_existing=yes',
        // a new registration replaces contacts that do not answer, e.g. of a closed WebSocket
        'remove_unavailable=yes',
        'qualify_frequency=30',
        '',
        '[auth-template](!)',
        'type=auth',
        'auth_type=md5',
        `realm=${REALM}`,
        '',
    );

    for (const sub of subscribers) {
        const password = secrets.passwords[sub.extension];
        lines.push(
            `; ---- ${sub.extension} (${sub.kind}) ----`,
            `[${sub.extension}](${sub.kind === 'sip' ? 'sip-endpoint' : 'webrtc-endpoint'})`,
            `auth=${sub.extension}`,
            `aors=${sub.extension}`,
            `callerid="${sub.name}" <${sub.extension}>`,
            '',
            `[${sub.extension}](aor-template)`,
            '',
            `[${sub.extension}](auth-template)`,
            `username=${sub.extension}`,
            `md5_cred=${md5Credential(sub.extension, password)}`,
            '',
        );
    }

    lines.push('#tryinclude iobroker/pjsip_custom.conf', '');
    return lines.join('\n');
}

function genRtp(config: GeneratorConfig): string {
    let start = toPort(config.rtpStart, 10000);
    let end = toPort(config.rtpEnd, 20000);
    if (end <= start) {
        start = 10000;
        end = 20000;
    }
    const lines = [HEADER, '[general]', `rtpstart=${start}`, `rtpend=${end}`, 'icesupport=yes'];
    const stun = sanitizeHost(config.stunServer).replace(/^stun:/, '');
    if (stun) {
        lines.push(`stunaddr=${stun}`);
    }
    for (const net of sanitizeHost(config.iceDenylist)
        .split(',')
        .map(n => n.trim())
        .filter(Boolean)) {
        lines.push(`ice_denylist=${net}`);
    }
    lines.push('');
    return lines.join('\n');
}

function genExtensions(config: GeneratorConfig, subscribers: GeneratorSubscriber[]): string {
    const lines = [HEADER, '[general]', 'static=yes', 'writeprotect=yes', 'clearglobalvars=no', '', `[${CONTEXT}]`];
    if (config.echoTest) {
        lines.push(
            `exten => ${ECHO_EXTENSION},1,Answer()`,
            ' same => n,Wait(1)',
            ' same => n,Playback(hello-world)',
            ' same => n,Echo()',
            ' same => n,Hangup()',
            '',
        );
    }
    for (const sub of subscribers) {
        // Ring all registered devices of the subscriber, not only the first contact
        lines.push(
            `exten => ${sub.extension},1,Dial(\${PJSIP_DIAL_CONTACTS(${sub.extension})},30)`,
            ' same => n,Hangup()',
            '',
        );
    }
    lines.push('#tryinclude iobroker/extensions_custom.conf', '');
    return lines.join('\n');
}

function genManager(config: GeneratorConfig, secrets: GeneratorSecrets): string {
    return [
        HEADER,
        '[general]',
        'enabled=yes',
        `port=${toPort(config.amiPort, 5038)}`,
        'bindaddr=127.0.0.1',
        'displayconnects=no',
        '',
        `[${AMI_USER}]`,
        `secret=${sanitizeName(secrets.amiSecret)}`,
        'deny=0.0.0.0/0.0.0.0',
        'permit=127.0.0.1/255.255.255.255',
        'read=system,call,reporting',
        'write=system,command,reporting',
        '',
    ].join('\n');
}

