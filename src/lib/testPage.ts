/**
 * File name of the phone bundle next to the test page: React + MUI + JsSIP from `src-www`, built by
 * `npm run build:www` into `build/static`. Asterisk serves it itself, so the page needs no CDN and
 * works without internet access.
 */
export const PHONE_FILE = 'phone.min.js';

/**
 * Page shell of the WebRTC phone, served by Asterisk at `https://<host>:<wssPort>/static/test.html`.
 * Opening it also makes the browser accept the self-signed certificate, which is required before
 * the WSS connection can work.
 *
 * @param defaultNumber number preset in the dial field
 */
export function generateTestPage(defaultNumber: string): string {
    return `<!doctype html>
<!-- generated by ioBroker asterisk-docker – do not edit -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>ioBroker Phone</title>
<style>
    html, body { margin: 0; background: Canvas; }
    noscript { display: block; padding: 24px; font-family: system-ui, sans-serif; }
</style>
</head>
<body>
<div id="root" data-number="${defaultNumber.replace(/[^0-9]/g, '')}"></div>
<noscript>This page requires JavaScript.</noscript>
<script src="${PHONE_FILE}"></script>
</body>
</html>
`;
}
